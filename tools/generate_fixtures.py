ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "fixtures" / "generated"
PILLOW_VERSION = "10.4.0"


def sample_image() -> Image.Image:
    image = Image.new("RGB", (16, 12), (225, 231, 239))
    for y in range(12):
        for x in range(16):
            if x < 5 and y < 5:
                image.putpixel((x, y), (220, 50, 50))
            elif x >= 11 and y >= 7:
                image.putpixel((x, y), (30, 70, 200))
    return image


def make_exif(*, offset: bool, gps: str | None, orientation: int) -> Image.Exif:
    exif = Image.Exif()
    exif[ExifTags.Base.DateTimeOriginal] = "2020:02:03 04:05:06"
    exif[ExifTags.Base.Orientation] = orientation
    if offset:
        exif[ExifTags.Base.OffsetTimeOriginal] = "+09:00"
    if gps is not None:
        latitude_degrees = 95 if gps == "invalid" else (0 if gps in ("zero", "zero-no-datum") else 35)
        longitude_degrees = 0 if gps in ("zero", "zero-no-datum") else 139
        minutes = 0 if gps in ("zero", "zero-no-datum") else 30
        rational = TiffImagePlugin.IFDRational
        gps_tags = {
            1: "S" if gps == "southwest-no-datum" else "N",
            2: (rational(latitude_degrees, 1), rational(minutes, 1), rational(0, 1)),
            3: "W" if gps == "southwest-no-datum" else "E",
            4: (rational(longitude_degrees, 1), rational(minutes, 1), rational(0, 1)),
        }
        if gps not in ("no-datum", "southwest-no-datum", "zero-no-datum"):
            gps_tags[18] = "TOKYO" if gps == "non-wgs84" else "WGS-84"
        if gps != "no-accuracy":
            gps_tags[31] = rational(15, 2)
        exif[ExifTags.Base.GPSInfo] = gps_tags
    return exif


def jpeg(*, offset: bool, gps: str | None, orientation: int) -> bytes:
    output = io.BytesIO()
    sample_image().save(
        output,
        format="JPEG",
        quality=90,
        subsampling=0,
        exif=make_exif(offset=offset, gps=gps, orientation=orientation),
    )
    return output.getvalue()


def plain_image(format_name: str, exif: Image.Exif | None = None) -> bytes:
    output = io.BytesIO()
    options = {"lossless": True} if format_name == "WEBP" else {}
    if exif is not None:
        options["exif"] = exif
    sample_image().save(output, format=format_name, **options)
    return output.getvalue()


def oversized_png_header() -> bytes:
    """A valid PNG signature/IHDR advertising huge dimensions, invalid image data."""
    original = bytearray(plain_image("PNG"))
    original[16:24] = struct.pack(">II", 50_000, 50_000)
    original[29:33] = struct.pack(">I", zlib.crc32(original[12:29]) & 0xFFFFFFFF)
    return bytes(original)


