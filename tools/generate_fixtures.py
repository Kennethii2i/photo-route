def build_outputs() -> dict[str, bytes]:
    if pillow_version != PILLOW_VERSION:
        raise RuntimeError(f"Pillow {PILLOW_VERSION} required, found {pillow_version}")
    outputs: dict[str, bytes] = {}
    records = []
    for name, payload, expected in files_and_expectations():
        outputs[name] = payload
        records.append(
            {
                "file": name,
                "sha256": hashlib.sha256(payload).hexdigest(),
                "byteLength": len(payload),
                "expected": expected,
            }
        )
    manifest = {
        "schemaVersion": 1,
        "generator": "tools/generate_fixtures.py",
        "generatorRequirements": {"python": "3.12", "Pillow": PILLOW_VERSION},
        "source": "synthetic pixels and metadata generated in this repository",
        "thirdPartyImageLicense": "not applicable: no third-party images",
        "additionalFixtureManifest": "fixtures/heif/manifest.json",
        "missingRequiredFormats": [],
        "files": records,
    }
    outputs["manifest.json"] = (json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8")
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="verify without changing files")
    args = parser.parse_args()
    outputs = build_outputs()
    if args.check:
        actual_names = {path.name for path in OUTPUT.iterdir() if path.is_file()} if OUTPUT.exists() else set()
        expected_names = set(outputs)
        mismatches = sorted(actual_names ^ expected_names)
        mismatches += sorted(name for name, data in outputs.items() if (OUTPUT / name).is_file() and (OUTPUT / name).read_bytes() != data)
        if mismatches:
            print("Fixture mismatch:", ", ".join(mismatches))
            return 1
        print(f"Verified {len(outputs) - 1} base images and manifest; HEIC/HEIF checked separately")
        return 0
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for name, data in outputs.items():
        (OUTPUT / name).write_bytes(data)
    print(f"Generated {len(outputs) - 1} base images and manifest; HEIC/HEIF generated separately")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
